import {
  useEffect,
  useRef,
  useState,
} from "react";

import {
  hasAnyInput,
  parseList,
} from "../chat/buildStructuredMessage";

import * as api from "../api";
import { SEVERITIES, type RiskType, type Severity } from "@disa/shared-types";
import { SeverityBadge } from "./SeverityBadge";
import { RiskTypeLabel } from "./RiskTypeLabel";
import { IconCheck, IconCode } from "./icons";

interface Props {
  onSubmit: (text: string) => void;
  onClose: () => void;
  busy: boolean;
  token: string;
}

interface RiskResult {
  id?: string;
  type?: string;
  severity?: string;
  summary?: string;
  drugsInvolved?: Array<{
    id?: string;
    name?: string;
  }>;
  cypher?: {
    label?: string;
    query?: string;
  };
  riskDescription?: string;
  tip?: string;
}

const RISK_TYPES: RiskType[] = ["interaction", "allergy", "contraindication"];

function isSeverity(value: string | undefined): value is Severity {
  return SEVERITIES.includes(value as Severity);
}

function isRiskType(value: string | undefined): value is RiskType {
  return RISK_TYPES.includes(value as RiskType);
}

/**
 * Structured input form for medication safety checking.
 *
 * This form does NOT depend on the chatbot response.
 *
 * Clicking "Check safety":
 *
 *   form values
 *       ↓
 *   api.checkRisk()
 *       ↓
 *   POST /risk-check
 *       ↓
 *   Neo4j name → Drug ID resolution
 *       ↓
 *   risk engine
 *       ↓
 *   Risk[]
 *       ↓
 *   results displayed here
 */
export function StructuredInputForm({
  onSubmit,
  onClose,
  busy,
  token,
}: Props) {
  const [
    medications,
    setMedications,
  ] = useState("");

  const [
    conditions,
    setConditions,
  ] = useState("");

  const [
    allergies,
    setAllergies,
  ] = useState("");

  const [
    results,
    setResults,
  ] = useState<RiskResult[] | null>(
    null
  );

  const [
    loading,
    setLoading,
  ] = useState(false);

  const [
    error,
    setError,
  ] = useState<string | undefined>(
    undefined
  );

  const [
    expandedCypher,
    setExpandedCypher,
  ] = useState<Record<string, boolean>>({});

  const firstFieldRef =
    useRef<HTMLInputElement>(null);

  useEffect(() => {
    firstFieldRef.current?.focus();
  }, []);

  useEffect(() => {
    function handleKeyDown(
      event: KeyboardEvent
    ) {
      if (event.key === "Escape") {
        onClose();
      }
    }

    window.addEventListener(
      "keydown",
      handleKeyDown
    );

    return () => {
      window.removeEventListener(
        "keydown",
        handleKeyDown
      );
    };
  }, [onClose]);

  const parsed = {
    medications:
      parseList(medications),

    conditions:
      parseList(conditions),

    allergies:
      parseList(allergies),
  };

  const canSubmit =
    hasAnyInput(parsed) &&
    !busy &&
    !loading;

  async function handleSubmit(
    event: React.FormEvent
  ) {
    event.preventDefault();

    if (!canSubmit) {
      return;
    }

    setLoading(true);
    setError(undefined);
    setResults(null);

    try {
      const data =
        await api.checkRisk(
          {
            medications:
              parsed.medications,

            allergies:
              parsed.allergies,

            conditions:
              parsed.conditions,
          },
          token
        );

      /**
       * The backend returns:
       *
       * {
       *   risks: [...]
       * }
       *
       * Keep those Risk objects intact.
       *
       * In particular:
       *
       * risk.cypher.query
       *
       * is generated by the backend using medication
       * NAMES, not IDs.
       */
      setResults(
        Array.isArray(data.risks)
          ? data.risks
          : []
      );
    } catch (err) {
      if (
        err instanceof api.ApiError
      ) {
        setError(err.message);
      } else {
        setError(
          "Failed to fetch risks."
        );
      }
    } finally {
      setLoading(false);
    }
  }

  return (
    <div
      className="modal-overlay"
      onMouseDown={onClose}
      role="presentation"
    >
      <div
        className="modal-card"
        role="dialog"
        aria-modal="true"
        aria-labelledby="structured-form-title"
        onMouseDown={(event) =>
          event.stopPropagation()
        }
      >
        <h2
          id="structured-form-title"
          className="modal-title"
        >
          Check by form
        </h2>

        <p className="modal-subtitle">
          List your medications,
          conditions, and allergies.
          Separate multiple entries
          with commas — I'll check them
          against the medication safety
          graph.
        </p>

        <form
          onSubmit={handleSubmit}
        >
          <div className="field">
            <label htmlFor="form-medications">
              Medications
            </label>

            <input
              id="form-medications"
              ref={firstFieldRef}
              type="text"
              value={medications}
              onChange={(event) =>
                setMedications(
                  event.target.value
                )
              }
              placeholder="e.g. warfarin, aspirin"
              disabled={
                busy || loading
              }
            />
          </div>

          <div className="field">
            <label htmlFor="form-conditions">
              Conditions
            </label>

            <input
              id="form-conditions"
              type="text"
              value={conditions}
              onChange={(event) =>
                setConditions(
                  event.target.value
                )
              }
              placeholder="e.g. hypertension, chronic kidney disease"
              disabled={
                busy || loading
              }
            />
          </div>

          <div className="field">
            <label htmlFor="form-allergies">
              Allergies
            </label>

            <input
              id="form-allergies"
              type="text"
              value={allergies}
              onChange={(event) =>
                setAllergies(
                  event.target.value
                )
              }
              placeholder="e.g. penicillin"
              disabled={
                busy || loading
              }
            />
          </div>

          <div className="modal-actions">
            <button
              type="button"
              className="btn btn-secondary"
              onClick={onClose}
              disabled={
                busy || loading
              }
            >
              Cancel
            </button>

            <button
              type="submit"
              className="btn btn-primary"
              disabled={!canSubmit}
            >
              {loading ? (
                <span className="spinner" />
              ) : (
                "Check safety"
              )}
            </button>
          </div>
        </form>

        {error && (
          <p className="error-msg">
            Error: {error}
          </p>
        )}

        {results !== null && (
          <div className="risk-results">
            <h3 className="risk-results-title">
              Risk Check Results
            </h3>

            {results.length === 0 ? (
              <div className="risk-empty">
                <span className="risk-empty-icon">
                  <IconCheck size={16} />
                </span>
                No known risks were found for
                the information provided.
              </div>
            ) : (
              <div className="risk-list">
                {results.map((risk, index) => {
                  const key =
                    risk.id ?? `risk-${index}`;
                  const cypherOpen =
                    Boolean(expandedCypher[key]);
                  const severity = isSeverity(
                    risk.severity
                  )
                    ? risk.severity
                    : undefined;
                  const type = isRiskType(
                    risk.type
                  )
                    ? risk.type
                    : undefined;

                  return (
                    <div
                      key={key}
                      className={`risk-item risk-item-${severity ?? "moderate"}`}
                      style={{
                        animationDelay: `${index * 60}ms`,
                      }}
                    >
                      <div className="risk-item-header">
                        {severity && (
                          <SeverityBadge
                            severity={severity}
                          />
                        )}

                        {type && (
                          <RiskTypeLabel
                            type={type}
                          />
                        )}
                      </div>

                      <p className="risk-item-summary">
                        {risk.summary ??
                          "Risk detected"}
                      </p>

                      {risk.riskDescription && (
                        <p className="risk-item-description">
                          {risk.riskDescription}
                        </p>
                      )}

                      {risk.tip && (
                        <p className="risk-item-tip">
                          <strong>Tip:</strong>{" "}
                          {risk.tip}
                        </p>
                      )}

                      {risk.cypher?.query && (
                        <div className="risk-item-cypher">
                          <button
                            type="button"
                            className="chat-risk-rail-cypher-btn"
                            onClick={() =>
                              setExpandedCypher(
                                (prev) => ({
                                  ...prev,
                                  [key]: !prev[
                                    key
                                  ],
                                })
                              )
                            }
                            aria-expanded={
                              cypherOpen
                            }
                          >
                            <IconCode size={13} />
                            {cypherOpen
                              ? "Hide Cypher query"
                              : "View Cypher query"}
                          </button>

                          {cypherOpen && (
                            <div className="chat-risk-rail-cypher-panel">
                              {risk.cypher.label && (
                                <div className="chat-risk-rail-cypher-label">
                                  {
                                    risk.cypher
                                      .label
                                  }
                                </div>
                              )}
                              <pre className="chat-risk-rail-cypher-code">
                                {
                                  risk.cypher
                                    .query
                                }
                              </pre>
                            </div>
                          )}
                        </div>
                      )}
                    </div>
                  );
                })}
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
}